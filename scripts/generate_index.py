#!/usr/bin/env python3
"""Generate index.md and index.html from per-paper metadata files.

Source of truth: <paper-dir>/paper.json in each paper directory.
See plan.html section 6 (the index contract).

Usage:
    python3 scripts/generate_index.py          # regenerate index.md + index.html
    python3 scripts/generate_index.py --check  # exit 1 if generated files are stale

Both generated files are committed so they read offline and in the repo;
CI verifies they are current by running --check.
"""

import json
import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Canonical public location of the built site. PDF links in the generated
# index files use absolute URLs so they resolve from anywhere: the repo
# file view, raw reads, a local disk copy, and the site itself. (Relative
# links 404 in the repo view now that PDFs are build products, not tracked
# files.) Keep in sync with SITE_URL in .github/workflows/papers.yml.
SITE_URL = "https://winstoncheong.github.io/arxiv-fixes"


def load_papers():
    papers = []
    for meta_path in sorted(ROOT.glob("*/paper.json")):
        d = meta_path.parent
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        for key in ("arxiv", "title", "entries"):
            if key not in meta:
                raise ValueError(f"{meta_path}: missing required key {key!r}")
        if not meta["entries"]:
            raise ValueError(f"{meta_path}: entries list is empty")
        for e in meta["entries"]:
            if "tex" not in e or "pdf" not in e:
                raise ValueError(f"{meta_path}: each entry needs 'tex' and 'pdf'")
        meta["_dir"] = d.name
        papers.append(meta)
    return papers


def arxiv_url(arxiv):
    return f"https://arxiv.org/abs/{arxiv}"


def render_md(papers):
    out = ["# arxiv-fixes index", ""]
    out.append(
        "<!-- Generated by scripts/generate_index.py from */paper.json. "
        "Do not hand-edit. -->"
    )
    out.append("")
    for p in papers:
        d = p["_dir"]
        out.append(f"## {p['arxiv']} - {p['title']}")
        out.append("")
        if p.get("authors"):
            out.append(f"Authors: {p['authors']}")
            out.append("")
        pdfs = " ".join(
            f"[PDF]({SITE_URL}/{d}/{e['pdf']})" for e in p["entries"]
        )
        out.append(pdfs)
        out.append("")
        out.append(f"arXiv: [{p['arxiv']}]({arxiv_url(p['arxiv'])})")
        out.append("")
        if p.get("status"):
            out.append(f"Status: {p['status']}")
            out.append("")
        if p.get("abstract"):
            out.append(f"**Abstract:** {p['abstract']}")
            out.append("")
        if p.get("changes"):
            out.append("Changes:")
            out.append("")
            for c in p["changes"]:
                out.append(f"* {c}")
            out.append("")
        if p.get("warnings"):
            for w in p["warnings"]:
                out.append(f"Warning: {w}")
            out.append("")
        if (ROOT / d / "readme.md").exists():
            out.append(f"More info on conversion [here](./{d}/readme.md)")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def render_html(papers):
    parts = []
    parts.append(
        "<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n"
        "<meta charset=\"UTF-8\">\n"
        "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n"
        "<title>arxiv-fixes index</title>\n"
        "<style>\n"
        ":root { color-scheme: light dark; }\n"
        "body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', system-ui, sans-serif;\n"
        "  line-height: 1.6; max-width: 46rem; margin: 0 auto; padding: 1.5rem; }\n"
        "article { border: 1px solid #8883; border-radius: 8px; padding: 1rem 1.2rem; margin: 1.2rem 0; }\n"
        "h1 { font-size: 1.6rem; } h2 { font-size: 1.15rem; margin-bottom: 0.2rem; }\n"
        ".meta { color: gray; font-size: 0.9rem; }\n"
        ".notice { border-left: 4px solid #0969da; padding: 0.5rem 1rem; background: #0969da11; }\n"
        "</style>\n</head>\n<body>\n"
        "<h1>arxiv-fixes index</h1>\n"
        "<p class=\"notice\">Generated by <code>scripts/generate_index.py</code> "
        "from <code>*/paper.json</code>. Do not hand-edit.</p>\n"
    )
    for p in papers:
        d = p["_dir"]
        parts.append("<article>\n")
        parts.append(f"<h2>{escape(p['arxiv'])} &ndash; {escape(p['title'])}</h2>\n")
        if p.get("authors"):
            parts.append(f"<p class=\"meta\">{escape(p['authors'])}</p>\n")
        for e in p["entries"]:
            parts.append(
                f"<p><a href=\"{SITE_URL}/{d}/{escape(e['pdf'])}\">PDF</a></p>\n"
            )
        parts.append(
            f"<p class=\"meta\">arXiv: <a href=\"{arxiv_url(escape(p['arxiv']))}\">"
            f"{escape(p['arxiv'])}</a>"
        )
        if p.get("status"):
            parts.append(f" &middot; Status: {escape(p['status'])}")
        parts.append("</p>\n")
        if p.get("abstract"):
            parts.append(f"<p><strong>Abstract:</strong> {escape(p['abstract'])}</p>\n")
        if p.get("changes"):
            parts.append("<p>Changes:</p>\n<ul>\n")
            for c in p["changes"]:
                parts.append(f"<li>{escape(c)}</li>\n")
            parts.append("</ul>\n")
        for w in p.get("warnings", []):
            parts.append(f"<p><strong>Warning:</strong> {escape(w)}</p>\n")
        if (ROOT / d / "readme.md").exists():
            parts.append(f"<p><a href=\"./{d}/readme.md\">Conversion notes</a></p>\n")
        parts.append("</article>\n")
    parts.append("</body>\n</html>\n")
    return "".join(parts)


def main(argv):
    check = "--check" in argv
    papers = load_papers()
    md, html = render_md(papers), render_html(papers)
    md_path, html_path = ROOT / "index.md", ROOT / "index.html"
    if check:
        stale = []
        if md_path.read_text(encoding="utf-8") != md:
            stale.append("index.md")
        if html_path.read_text(encoding="utf-8") != html:
            stale.append("index.html")
        if stale:
            print(f"stale generated files: {', '.join(stale)}; "
                  "run scripts/generate_index.py", file=sys.stderr)
            return 1
        print("index.md and index.html are current.")
        return 0
    md_path.write_text(md, encoding="utf-8")
    html_path.write_text(html, encoding="utf-8")
    print(f"wrote index.md and index.html from {len(papers)} paper.json files.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
